func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintf(os.Stderr, "error: %v\n", err)
		os.Exit(1)
	}
}

func run(args []string) error {
	if len(args) == 0 {
		printUsage()
		return nil
	}

	switch args[0] {
	case "init":
		return cmdInit(args[1:])
	case "serve":
		return cmdServe(args[1:])
	case "admin":
		return cmdAdmin(args[1:])
	case "version":
		fmt.Printf("opendotnews %s\n", opendotnews.Version)
		return nil
	case "-h", "--help", "help":
		printUsage()
		return nil
	default:
		printUsage()
		return fmt.Errorf("unknown command %q", args[0])
	}
}

func printUsage() {
	fmt.Println(`opendotnews — embeddable, self-hostable publish/subscribe hub for agents

Usage:
  opendotnews init [--data-dir ./data] [--config ./opendotnews.yaml]
  opendotnews serve [--config ./opendotnews.yaml]
  opendotnews admin <resource> <action> [flags]
  opendotnews version

Admin commands:
  opendotnews admin account create <subject> [--config ./opendotnews.yaml]
  opendotnews admin token create --account <id> [--scopes s1,s2] [--admin] [--config ./opendotnews.yaml]
  opendotnews admin namespace create <name> --account <id> [--config ./opendotnews.yaml]
  opendotnews admin subscriptions list [--config ./opendotnews.yaml] [--url http://127.0.0.1:8080 --admin-token ...]
  opendotnews admin subscriptions retry <subscription-id> [--url http://127.0.0.1:8080 --admin-token ...] [--config ./opendotnews.yaml]
  opendotnews admin failures list [--subscription <id>] [--config ./opendotnews.yaml]`)
}

func cmdInit(args []string) error {
	fs := flag.NewFlagSet("init", flag.ContinueOnError)
	dataDir := fs.String("data-dir", "./data", "directory for SQLite database, master key, and JetStream storage")
	configPath := fs.String("config", "./opendotnews.yaml", "path to write starter configuration file")
	force := fs.Bool("force", false, "overwrite existing config file")
	if err := fs.Parse(args); err != nil {
		return err
	}

	if err := os.MkdirAll(*dataDir, 0o750); err != nil {
		return fmt.Errorf("create data dir: %w", err)
	}

	cfg := opendotnews.DefaultConfig()
	cfg.DataDir = *dataDir
	cfg.NATS.StoreDir = filepath.Join(*dataDir, "jetstream")
	cfg.Secrets.MasterKeyFile = filepath.Join(*dataDir, "master.key")
	adminTok, err := domain.NewOpaqueToken("odn_admin")
	if err != nil {
		return err
	}
	cfg.Auth.AdminToken = adminTok

	// Pre-initialize master key and SQLite migrations.
	if _, err := secret.LoadOrCreateMasterKey("", cfg.Secrets.MasterKeyFile); err != nil {
		return err
	}
	st, err := sqlite.Open(context.Background(), cfg.DBPath())
	if err != nil {
		return err
	}
	_ = st.Close()

	if _, err := os.Stat(*configPath); err == nil && !*force {
		fmt.Printf("Initialized data directory at %s (kept existing config %s)\n", *dataDir, *configPath)
		return nil
	}

	out, err := yaml.Marshal(&cfg)
	if err != nil {
		return err
	}
	header := "# opendotnews local configuration (generated by `opendotnews init`)\n# WARNING: Loopback HTTP settings are for local development only — configure TLS and strict egress for production.\n\n"
	if err := os.WriteFile(*configPath, append([]byte(header), out...), 0o600); err != nil {
		return err
	}

	fmt.Printf("Initialized opendotnews:\n  data_dir:    %s\n  config:      %s\n  admin_token: %s\n", *dataDir, *configPath, adminTok)
	return nil
}

func cmdServe(args []string) error {
	fs := flag.NewFlagSet("serve", flag.ContinueOnError)
	configPath := fs.String("config", "./opendotnews.yaml", "path to YAML configuration file")
	if err := fs.Parse(args); err != nil {
		return err
	}

	cfg, err := opendotnews.LoadConfigFile(*configPath)
	if err != nil {
		return err
	}

	logger := slog.New(slog.NewJSONHandler(os.Stdout, &slog.HandlerOptions{Level: slog.LevelInfo}))
	hub, err := opendotnews.New(cfg, opendotnews.Dependencies{Logger: logger})
	if err != nil {
		return err
	}

	ctx, stop := signal.NotifyContext(context.Background(), syscall.SIGINT, syscall.SIGTERM)
	defer stop()

	if err := hub.Start(ctx); err != nil {
		return err
	}

	<-ctx.Done()
	logger.Info("shutting down opendotnews hub")
	shutdownCtx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()
	return hub.Shutdown(shutdownCtx)
}

func cmdAdmin(args []string) error {
	if len(args) < 2 {
		printUsage()
		return errors.New("admin requires a resource and action")
	}
	resource, action, rest := args[0], args[1], args[2:]
	switch resource + " " + action {
	case "account create":
		return adminAccountCreate(rest)
	case "token create":
		return adminTokenCreate(rest)
	case "namespace create":
		return adminNamespaceCreate(rest)
	case "subscriptions list":
		return adminSubscriptionsList(rest)
	case "subscriptions retry":
		return adminSubscriptionsRetry(rest)
	case "failures list":
		return adminFailuresList(rest)
	default:
		printUsage()
		return fmt.Errorf("unknown admin command %q %q", resource, action)
	}
}

func adminAccountCreate(args []string) error {
	fs := flag.NewFlagSet("account create", flag.ContinueOnError)
	cfgPath := fs.String("config", "./opendotnews.yaml", "config file")
	if err := parseFlexible(fs, args); err != nil {
		return err
	}
	if fs.NArg() < 1 {
		return errors.New("usage: opendotnews admin account create <subject>")
	}
	subject := fs.Arg(0)

	st, err := openStoreFromConfig(*cfgPath)
	if err != nil {
		return err
	}
	defer st.Close()

	acc := domain.Account{
		ID:              domain.NewID("acc"),
		ExternalSubject: subject,
		Status:          domain.AccountStatusActive,
		CreatedAt:       time.Now().UTC(),
	}
	if err := st.CreateAccount(context.Background(), acc); err != nil {
		return err
	}
	fmt.Printf("account_id=%s subject=%s status=%s\n", acc.ID, acc.ExternalSubject, acc.Status)
	return nil
}

func adminTokenCreate(args []string) error {
	fs := flag.NewFlagSet("token create", flag.ContinueOnError)
	cfgPath := fs.String("config", "./opendotnews.yaml", "config file")
	accountID := fs.String("account", "", "account ID")
	scopesFlag := fs.String("scopes", "events:publish,subscriptions:write,subscriptions:read", "comma-separated scopes")
	isAdmin := fs.Bool("admin", false, "grant admin privileges")
	if err := parseFlexible(fs, args); err != nil {
		return err
	}
	if *accountID == "" {
		return errors.New("--account is required")
	}

	st, err := openStoreFromConfig(*cfgPath)
	if err != nil {
		return err
	}
	defer st.Close()

	acc, err := st.GetAccount(context.Background(), *accountID)
	if err != nil {
		return err
	}
	raw, err := domain.NewOpaqueToken("odn")
	if err != nil {
		return err
	}
	var scopes []string
	for _, s := range strings.Split(*scopesFlag, ",") {
		s = strings.TrimSpace(s)
		if s != "" {
			scopes = append(scopes, s)
		}
	}
	rec := store.LocalTokenRecord{
		ID:        domain.NewID("tok"),
		AccountID: acc.ID,
		Subject:   acc.ExternalSubject,
		TokenHash: auth.HashToken(raw),
		Scopes:    scopes,
		IsAdmin:   *isAdmin,
		CreatedAt: time.Now().UTC(),
	}
	if err := st.CreateLocalToken(context.Background(), rec); err != nil {
		return err
	}
	fmt.Printf("token_id=%s account_id=%s token=%s\n", rec.ID, rec.AccountID, raw)
	return nil
}

func adminNamespaceCreate(args []string) error {
	fs := flag.NewFlagSet("namespace create", flag.ContinueOnError)
	cfgPath := fs.String("config", "./opendotnews.yaml", "config file")
	accountID := fs.String("account", "", "owner account ID")
	if err := parseFlexible(fs, args); err != nil {
		return err
	}
	if fs.NArg() < 1 || *accountID == "" {
		return errors.New("usage: opendotnews admin namespace create <name> --account <id>")
	}
	canonical, err := domain.ValidateNamespace(fs.Arg(0))
	if err != nil {
		return err
	}

	st, err := openStoreFromConfig(*cfgPath)
	if err != nil {
		return err
	}
	defer st.Close()

	ns := domain.Namespace{
		ID:            domain.NewID("ns"),
		AccountID:     *accountID,
		CanonicalName: canonical,
		CreatedAt:     time.Now().UTC(),
	}
	if err := st.ClaimNamespace(context.Background(), ns); err != nil {
		return err
	}
	fmt.Printf("namespace_id=%s namespace=%s account_id=%s\n", ns.ID, ns.CanonicalName, ns.AccountID)
	return nil
}

func adminSubscriptionsList(args []string) error {
	fs := flag.NewFlagSet("subscriptions list", flag.ContinueOnError)
	cfgPath := fs.String("config", "./opendotnews.yaml", "config file")
	if err := fs.Parse(args); err != nil {
		return err
	}
	st, err := openStoreFromConfig(*cfgPath)
	if err != nil {
		return err
	}
	defer st.Close()

	subs, err := st.ListSubscriptions(context.Background())
	if err != nil {
		return err
	}
	tw := tabwriter.NewWriter(os.Stdout, 0, 4, 2, ' ', 0)
	fmt.Fprintln(tw, "ID\tACCOUNT\tCHANNEL\tMODE\tSTATUS\tLAST_SEQ\tENDPOINT\tLAST_ERROR")
	for _, s := range subs {
		fmt.Fprintf(tw, "%s\t%s\t%s\t%s\t%s\t%d\t%s\t%s\n",
			s.ID, s.AccountID, s.CanonicalChannel, s.DeliveryMode, s.Status, s.LastDeliveredSeq, s.Endpoint, s.LastError)
	}
	return tw.Flush()
}

func adminSubscriptionsRetry(args []string) error {
	fs := flag.NewFlagSet("subscriptions retry", flag.ContinueOnError)
	cfgPath := fs.String("config", "./opendotnews.yaml", "config file")
	serverURL := fs.String("url", "", "running hub base URL (e.g. http://127.0.0.1:8080)")
	adminToken := fs.String("admin-token", "", "admin bearer token for live HTTP retry")
	if err := parseFlexible(fs, args); err != nil {
		return err
	}
	if fs.NArg() < 1 {
		return errors.New("usage: opendotnews admin subscriptions retry <subscription-id>")
	}
	subID := fs.Arg(0)

	if *serverURL != "" {
		tok := *adminToken
		if tok == "" {
			if cfg, err := opendotnews.LoadConfigFile(*cfgPath); err == nil {
				tok = cfg.Auth.AdminToken
			}
		}
		req, err := http.NewRequest(http.MethodPost, strings.TrimRight(*serverURL, "/")+"/admin/subscriptions/"+subID+"/retry", bytes.NewReader(nil))
		if err != nil {
			return err
		}
		if tok != "" {
			req.Header.Set("Authorization", "Bearer "+tok)
		}
		resp, err := http.DefaultClient.Do(req)
		if err != nil {
			return err
		}
		defer resp.Body.Close()
		body, _ := io.ReadAll(resp.Body)
		if resp.StatusCode >= 300 {
			return fmt.Errorf("server returned HTTP %d: %s", resp.StatusCode, strings.TrimSpace(string(body)))
		}
		var pretty bytes.Buffer
		_ = json.Indent(&pretty, body, "", "  ")
		fmt.Println(pretty.String())
		return nil
	}

	st, err := openStoreFromConfig(*cfgPath)
	if err != nil {
		return err
	}
	defer st.Close()
	if err := st.UpdateSubscriptionStatus(context.Background(), subID, domain.SubscriptionStatusActive, ""); err != nil {
		return err
	}
	fmt.Printf("subscription %s marked active (restart hub or pass --url to wake immediately)\n", subID)
	return nil
}

func adminFailuresList(args []string) error {
	fs := flag.NewFlagSet("failures list", flag.ContinueOnError)
	cfgPath := fs.String("config", "./opendotnews.yaml", "config file")
	subID := fs.String("subscription", "", "filter by subscription ID")
	limit := fs.Int("limit", 50, "maximum rows")
	if err := fs.Parse(args); err != nil {
		return err
	}
	st, err := openStoreFromConfig(*cfgPath)
	if err != nil {
		return err
	}
	defer st.Close()

	failures, err := st.ListDeliveryFailures(context.Background(), *subID, *limit)
	if err != nil {
		return err
	}
	tw := tabwriter.NewWriter(os.Stdout, 0, 4, 2, ' ', 0)
	fmt.Fprintln(tw, "RECORDED_AT\tSUBSCRIPTION\tEVENT_ID\tCATEGORY\tHTTP\tATTEMPTS\tERROR")
	for _, f := range failures {
		fmt.Fprintf(tw, "%s\t%s\t%s\t%s\t%d\t%d\t%s\n",
			f.RecordedAt.Format(time.RFC3339), f.SubscriptionID, f.EventID, f.FailureCategory, f.HTTPStatus, f.Attempts, f.ErrorMessage)
	}
	return tw.Flush()
}

func openStoreFromConfig(cfgPath string) (*sqlite.SQLiteStore, error) {
	cfg, err := opendotnews.LoadConfigFile(cfgPath)
	if err != nil {
		return nil, err
	}
	return sqlite.Open(context.Background(), cfg.DBPath())
}

// parseFlexible lets flags appear before or after positional arguments (unlike stdlib flag.Parse).
func parseFlexible(fs *flag.FlagSet, args []string) error {
	var flags, positionals []string
	for i := 0; i < len(args); i++ {
		arg := args[i]
		if arg == "--" {
			positionals = append(positionals, args[i+1:]...)
			break
		}
		if strings.HasPrefix(arg, "-") && arg != "-" {
			flags = append(flags, arg)
			if !strings.Contains(arg, "=") {
				name := strings.TrimLeft(arg, "-")
				f := fs.Lookup(name)
				isBool := false
				if f != nil {
					type boolFlag interface{ IsBoolFlag() bool }
					if bf, ok := f.Value.(boolFlag); ok && bf.IsBoolFlag() {
						isBool = true
					}
				}
				if !isBool && i+1 < len(args) {
					i++
					flags = append(flags, args[i])
				}
			}
		} else {
			positionals = append(positionals, arg)
		}
	}
	return fs.Parse(append(flags, positionals...))
}
